CREATE TABLE suppliers (
    id UUID PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    contact_email VARCHAR(255)
);
CREATE TABLE products (
    id UUID PRIMARY KEY,
    sku VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    unit VARCHAR(20) NOT NULL
);
CREATE TABLE stores (
    id UUID PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    region VARCHAR(100) NOT NULL,
    format VARCHAR(30) NOT NULL
);
CREATE TABLE promo_campaigns (
    id UUID PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    product_id UUID NOT NULL REFERENCES products(id),
    supplier_id UUID NOT NULL REFERENCES suppliers(id),
    status VARCHAR(30) NOT NULL,
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    regular_price NUMERIC(12,2) NOT NULL,
    promo_price NUMERIC(12,2) NOT NULL,
    supplier_purchase_price NUMERIC(12,2) NOT NULL,
    planned_quantity INTEGER NOT NULL,
    actual_quantity INTEGER NOT NULL DEFAULT 0,
    marketing_contribution NUMERIC(12,2) NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE campaign_allocations (
    id UUID PRIMARY KEY,
    campaign_id UUID NOT NULL REFERENCES promo_campaigns(id) ON DELETE CASCADE,
    store_id UUID NOT NULL REFERENCES stores(id),
    planned_quantity INTEGER NOT NULL,
    sold_quantity INTEGER NOT NULL DEFAULT 0,
    UNIQUE(campaign_id, store_id)
);
